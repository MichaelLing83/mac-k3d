    fn mode(path: &Path) -> u32 {
        use std::os::unix::fs::PermissionsExt;
        std::fs::metadata(path).unwrap().permissions().mode() & 0o777
    }

    #[test]
    fn the_secret_lives_in_a_private_file_not_the_launch_script() {
        let tmp = tempfile::tempdir().unwrap();
        let script = tmp.path().join("launch-agent.sh");
        let jar = tmp.path().join("agent.jar");
        let secret = "0123abcd0123abcd";
        assert!(
            write_launch_script_with_java(&script, "http://c:8080", "n", &jar, secret, "java")
                .unwrap()
        );
        let body = std::fs::read_to_string(&script).unwrap();
        let file = tmp.path().join(SECRET_FILE);
        assert!(!body.contains(secret), "{body}");
        assert!(
            body.contains(&format!("-secret \"@{}\"", file.display())),
            "{body}"
        );
        assert_eq!(std::fs::read_to_string(&file).unwrap(), format!("{secret}\n"));
        assert_eq!(mode(&script), 0o700);
        assert_eq!(mode(&file), 0o600);
        assert!(has_agent_secret(&script));

        // A new secret alone restarts the agent; a wider mode is tightened on the next run.
        assert!(
            write_launch_script_with_java(&script, "http://c:8080", "n", &jar, "ffff0000", "java")
                .unwrap()
        );
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&file, std::fs::Permissions::from_mode(0o644)).unwrap();
        }
        assert!(
            !write_launch_script_with_java(&script, "http://c:8080", "n", &jar, "ffff0000", "java")
                .unwrap()
        );
        assert_eq!(mode(&file), 0o600);
    }

    #[test]
    fn an_inline_secret_from_an_old_script_moves_to_the_file() {
        let tmp = tempfile::tempdir().unwrap();
        let script = tmp.path().join("launch-agent.sh");
        let jar = tmp.path().join("agent.jar");
        std::fs::write(
            &script,
            "#!/usr/bin/env bash\nexec \"java\" -jar \"agent.jar\" \\\n  -url \"http://c:8080\" \\\n  -secret \"oldhex42\" \\\n  -name \"n\" \\\n  -webSocket\n",
        )
        .unwrap();
        assert_eq!(existing_secret(&script).as_deref(), Some("oldhex42"));
        let kept = existing_secret(&script).unwrap();
        assert!(
            write_launch_script_with_java(&script, "http://c:8080", "n", &jar, &kept, "java")
                .unwrap()
        );
        assert!(!std::fs::read_to_string(&script).unwrap().contains("oldhex42"));
        assert_eq!(existing_secret(&script).as_deref(), Some("oldhex42"));
    }

